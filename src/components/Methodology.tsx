function QualityBadge({ q }: { q: Quality }) {
  return <span className={`shrink-0 rounded-full border px-1.5 py-px text-[9px] uppercase tracking-[0.12em] ${QUALITY_STYLE[q]}`}>{q}</span>;
}

function ParamRow({ name, p }: { name: string; p: Param }) {
  return (
    <li className="border-b border-white/5 py-2 last:border-0">
      <div className="flex items-baseline gap-2">
        <span className="flex-1 text-parchment">{name}</span>
        <span className="num text-parchment">{p.value.toLocaleString('en-US', { maximumFractionDigits: 3 })} <span className="text-slate">{p.unit}</span></span>
        <QualityBadge q={p.quality} />
      </div>
      <div className="mt-0.5 text-[11px] leading-snug text-slate">{p.source}{p.note ? ` — ${p.note}` : ''}</div>
    </li>
  );
}

function H({ children }: { children: React.ReactNode }) {
  return <h3 className="eyebrow mb-2 mt-7 first:mt-0">{children}</h3>;
}

